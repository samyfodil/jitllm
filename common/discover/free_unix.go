//go:build unix

package discover

import "syscall"

// FreeBytes is the space free to this user on dir's filesystem.
func FreeBytes(dir string) (int64, bool) {
	var st syscall.Statfs_t
	if err := syscall.Statfs(dir, &st); err != nil {
		return 0, false
	}
	return int64(st.Bavail) * int64(st.Bsize), true
}
